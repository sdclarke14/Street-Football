// Parents first. The mixer does not care, but it keeps this readable next to
// the procedural solver in anim.js, which does.
export const CATCH_BONES = ["Hips", "Spine02", "Spine01", "Spine", "neck", "Head", "LeftShoulder", "LeftArm", "LeftForeArm", "LeftHand", "RightShoulder", "RightArm", "RightForeArm", "RightHand"];

export function buildCatchClip(THREE) {
  const t = CATCH_CLIP.times;
  const tracks = CATCH_BONES.map(
    (b) => new THREE.QuaternionKeyframeTrack(b + '.quaternion', t, CATCH_CLIP.rot[b])
  );
  tracks.push(new THREE.VectorKeyframeTrack('Hips.position', t, CATCH_CLIP.hipsPos));
  return new THREE.AnimationClip(CATCH_CLIP.name, CATCH_CLIP.duration, tracks);
}

// Sampling the clip ourselves rather than handing it to AnimationMixer.
//
// The run cycle animates the spine and arms too. Two mixer actions writing the
// same bone blend in proportion to their weights, so a catch action at weight 1
// alongside a run action at weight 1 lands halfway between them - a visibly
// half-committed catch. Fading the run down instead would take the legs with
// it, and the legs are the one part that should keep running.
//
// So the clip is applied the way the procedural poses already are: after
// mixer.update(), straight onto the bones, weighted. Keyframed data, same
// plumbing.
export function makeCatchSampler(THREE) {
  const rot = {};
  for (const b of CATCH_BONES) rot[b] = new THREE.Quaternion();
  const hipsPos = new THREE.Vector3();
  const qa = new THREE.Quaternion();
  const qb = new THREE.Quaternion();
  const t = CATCH_CLIP.times;
  const out = { rot, hipsPos };

  return function sampleCatch(time) {
    const tt = Math.max(t[0], Math.min(CATCH_CLIP.duration, time));
    let i = 1;
    while (i < t.length - 1 && t[i] < tt) i++;
    const a = t[i] > t[i - 1] ? (tt - t[i - 1]) / (t[i] - t[i - 1]) : 0;
    const p = i - 1;
    for (const b of CATCH_BONES) {
      const r = CATCH_CLIP.rot[b];
      qa.set(r[p * 4], r[p * 4 + 1], r[p * 4 + 2], r[p * 4 + 3]);
      qb.set(r[i * 4], r[i * 4 + 1], r[i * 4 + 2], r[i * 4 + 3]);
      rot[b].copy(qa).slerp(qb, a);
    }
    const h = CATCH_CLIP.hipsPos;
    hipsPos.set(
      h[p * 3] + (h[i * 3] - h[p * 3]) * a,
      h[p * 3 + 1] + (h[i * 3 + 1] - h[p * 3 + 1]) * a,
      h[p * 3 + 2] + (h[i * 3 + 2] - h[p * 3 + 2]) * a
    );
    return out;
  };
}

// Ease in fast so the catch reads as a reaction, out slowly so it settles back
// into the run instead of snapping. Same shape the procedural poses use.
export function catchWeight(t) {
  if (t < 0 || t > CATCH_CLIP.duration) return 0;
  const inW = Math.min(1, t / 0.10);
  const outW = Math.min(1, (CATCH_CLIP.duration - t) / 0.22);
  return Math.min(inW, outW);
}
